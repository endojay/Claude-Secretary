#!/usr/bin/env python3
"""세후 월 수령액 → 세전 월급 역산기 (캠프나인치과 병원 인사용)

원장님은 월급을 '세후 받는 금액'으로 협상한다. 근로계약서에는 세전 금액을 적어야 하므로,
협상한 세후 금액에서 세전 기본급을 거꾸로 계산한다.

사용 예:
  python3 tools/세후역산.py 2300000                    # 세후 230만 원, 식대 20만 포함, 본인 1명, 2027년 요율
  python3 tools/세후역산.py 2300000 --식대 200000 --가족 2 --연도 2026 --월시간 177.3
  python3 tools/세후역산.py --세전 2500000            # 반대로 세전 → 세후 확인

정확도:
  - 4대보험: 공식 요율로 계산 (원 단위 절사 방식 차이로 몇십 원 차이 가능)
  - 소득세: 국세청 간이세액표를 만드는 계산 공식으로 근사한다. 실제 표와 월 몇천 원 차이가 날 수 있다.
    최종 금액은 세무사·급여 프로그램 또는 홈택스 간이세액표로 확인한다.
  - 8~20세 자녀 세액공제, 기준소득월액(국민연금은 전년도 신고 기준) 차이는 반영하지 않는다.
"""
import argparse

# ── 연도별 근로자 부담 요율 ───────────────────────────────────────────
요율 = {
    2026: dict(국민연금=0.0475, 건강=0.03595, 장기요양_건보대비=0.9448 / 7.19, 고용=0.009),
    # 2027: 건강 7.19% 동결, 장기요양 0.9994%(건보료 대비 13.90%) 확정(2026-10 발표).
    #       국민연금 10%(근로자 5%) — 2025년 개정 국민연금법(2026년 9.5%부터 매년 0.5%p 인상, 2033년 13%), 2026-11-20 확인.
    2027: dict(국민연금=0.05, 건강=0.03595, 장기요양_건보대비=0.9994 / 7.19, 고용=0.009),
}
최저임금 = {2026: 10320, 2027: 10700}
국민연금_상한, 국민연금_하한 = 6_370_000, 400_000  # 기준소득월액 상·하한(근사값). 일반 직원 급여에는 영향 없음.


def 절사(x, 단위=10):
    return int(x // 단위 * 단위)


def 사대보험(과세월급, 연도):
    r = 요율[연도]
    기준 = min(max(과세월급, 국민연금_하한), 국민연금_상한) // 1000 * 1000
    연금 = 절사(기준 * r["국민연금"])
    건강 = 절사(과세월급 * r["건강"])
    장기 = 절사(건강 * r["장기요양_건보대비"])
    고용 = 절사(과세월급 * r["고용"])
    return dict(국민연금=연금, 건강보험=건강, 장기요양=장기, 고용보험=고용)


def 근로소득공제(총급여):
    구간 = [(5_000_000, 0, 0.70, 0), (15_000_000, 3_500_000, 0.40, 5_000_000),
          (45_000_000, 7_500_000, 0.15, 15_000_000), (100_000_000, 12_000_000, 0.05, 45_000_000)]
    for 상한, 기본, 율, 초과기준 in 구간:
        if 총급여 <= 상한:
            return 기본 + (총급여 - 초과기준) * 율 if 기본 else 총급여 * 율
    return min(14_750_000 + (총급여 - 100_000_000) * 0.02, 20_000_000)


def 특별소득공제(총급여, 가족):
    """간이세액표 산정용 '특별소득공제 등' 근사 공식 (소득세법 시행령 별표2 비고 구조)."""
    if 가족 <= 1:
        if 총급여 <= 30_000_000:   return 3_100_000 + 총급여 * 0.04
        if 총급여 <= 45_000_000:   return 3_100_000 + 총급여 * 0.04 - (총급여 - 30_000_000) * 0.05
        if 총급여 <= 70_000_000:   return 3_100_000 + 총급여 * 0.015
        return 3_100_000 + 총급여 * 0.005
    if 가족 == 2:
        if 총급여 <= 30_000_000:   return 3_600_000 + 총급여 * 0.04
        if 총급여 <= 45_000_000:   return 3_600_000 + 총급여 * 0.04 - (총급여 - 30_000_000) * 0.05
        if 총급여 <= 70_000_000:   return 3_600_000 + 총급여 * 0.02
        return 3_600_000 + 총급여 * 0.01
    if 총급여 <= 30_000_000:       return 5_000_000 + 총급여 * 0.07
    if 총급여 <= 45_000_000:       return 5_000_000 + 총급여 * 0.07 - (총급여 - 30_000_000) * 0.05
    if 총급여 <= 70_000_000:       return 5_000_000 + 총급여 * 0.05
    return 5_000_000 + 총급여 * 0.03


def 산출세액(과표):
    구간 = [(14_000_000, 0.06, 0), (50_000_000, 0.15, 1_260_000), (88_000_000, 0.24, 5_760_000),
          (150_000_000, 0.35, 15_440_000), (300_000_000, 0.38, 19_940_000)]
    for 상한, 율, 누진공제 in 구간:
        if 과표 <= 상한:
            return max(과표 * 율 - 누진공제, 0)
    return 과표 * 0.40 - 25_940_000


def 근로소득세액공제(산출, 총급여):
    공제 = 산출 * 0.55 if 산출 <= 1_300_000 else 715_000 + (산출 - 1_300_000) * 0.30
    if 총급여 <= 33_000_000:
        한도 = 740_000
    elif 총급여 <= 70_000_000:
        한도 = max(660_000, 740_000 - (총급여 - 33_000_000) * 0.008)
    else:
        한도 = max(500_000, 660_000 - (총급여 - 70_000_000) * 0.5)
    return min(공제, 한도)


def 월소득세(과세월급, 가족, 연도):
    총급여 = 과세월급 * 12
    연금연액 = 사대보험(과세월급, 연도)["국민연금"] * 12
    과표 = (총급여 - 근로소득공제(총급여) - 1_500_000 * max(가족, 1)
            - 연금연액 - 특별소득공제(총급여, 가족))
    과표 = max(과표, 0)
    산출 = 산출세액(과표)
    결정 = max(산출 - 근로소득세액공제(산출, 총급여), 0)
    소득세 = 절사(결정 / 12)
    return 소득세, 절사(소득세 * 0.1)


def 세후계산(과세월급, 식대, 가족, 연도):
    보험 = 사대보험(과세월급, 연도)
    소득세, 지방세 = 월소득세(과세월급, 가족, 연도)
    공제합 = sum(보험.values()) + 소득세 + 지방세
    return dict(**보험, 소득세=소득세, 지방소득세=지방세, 공제합계=공제합,
                세후수령액=과세월급 + 식대 - 공제합)


def 세전역산(목표세후, 식대, 가족, 연도):
    lo, hi = 0, 목표세후 * 2
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if 세후계산(mid, 식대, 가족, 연도)["세후수령액"] >= 목표세후:
            hi = mid
        else:
            lo = mid
    return 절사(hi + 9, 10)  # 10원 단위로 올림 → 세후가 목표 이상이 되도록


def 출력(과세월급, 식대, 가족, 연도, 월시간, 목표=None):
    d = 세후계산(과세월급, 식대, 가족, 연도)
    통상시급 = 과세월급 / 월시간
    최저 = 최저임금.get(연도)
    w = lambda n: f"{n:>12,}원"
    print(f"\n[{연도}년 요율 · 공제대상가족 {가족}명 · 월 소정근로 {월시간}시간]")
    if 목표:
        print(f"  협상한 세후 수령액     {w(목표)}")
    print(f"  ▶ 계약서 기본급(세전)  {w(과세월급)}")
    print(f"  ▶ 식대(비과세)         {w(식대)}")
    print(f"  ▶ 월 급여 총액(세전)   {w(과세월급 + 식대)}")
    print(f"  ─ 공제 내역")
    for k in ["국민연금", "건강보험", "장기요양", "고용보험", "소득세", "지방소득세"]:
        print(f"      {k:<8}{w(d[k])}")
    print(f"      {'공제 합계':<7}{w(d['공제합계'])}")
    print(f"  = 세후 수령액(예상)    {w(d['세후수령액'])}")
    print(f"  통상시급 = 기본급 ÷ {월시간} = {통상시급:,.0f}원", end="")
    if 최저:
        ok = "✅ 최저임금 이상" if 통상시급 >= 최저 else "❌ 최저임금 미달!"
        print(f"  ({연도}년 최저임금 {최저:,}원 → {ok})")
    else:
        print()
    print(f"  연 환산(세전, 식대 포함) {(과세월급 + 식대) * 12:,}원 (퇴직금 별도)")
    print(f"  병원 부담 4대보험도 대략 같은 금액 + 산재보험이 추가로 듭니다.")
    print("  ※ 소득세는 간이세액표 근사 계산(월 몇천 원 오차 가능). 최종 금액은 세무사·급여프로그램으로 확인.\n")


if __name__ == "__main__":
    p = argparse.ArgumentParser(description="세후 월 수령액 → 세전 월급 역산")
    p.add_argument("세후", nargs="?", type=int, help="협상한 세후 월 수령액(식대 포함)")
    p.add_argument("--세전", type=int, help="세전 기본급을 넣으면 세후를 계산")
    p.add_argument("--식대", type=int, default=200_000, help="비과세 식대 (기본 200,000)")
    p.add_argument("--가족", type=int, default=1, help="공제대상가족 수(본인 포함, 기본 1)")
    p.add_argument("--연도", type=int, default=2027, choices=sorted(요율))
    p.add_argument("--월시간", type=float, default=177.3, help="월 소정근로시간(주휴 포함, 기본 177.3)")
    a = p.parse_args()
    if a.세전:
        출력(a.세전, a.식대, a.가족, a.연도, a.월시간)
    elif a.세후:
        출력(세전역산(a.세후, a.식대, a.가족, a.연도), a.식대, a.가족, a.연도, a.월시간, 목표=a.세후)
    else:
        p.print_help()
